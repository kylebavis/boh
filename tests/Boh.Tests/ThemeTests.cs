using System.Security.Claims;
using System.Text.Json;
using Boh.Web;
using Boh.Web.Data.Entities;
using Boh.Web.Security;

namespace Boh.Tests;

/// <summary>
/// Guards the seams between the four places a theme id has to line up: the C# list, the
/// generated stylesheet, the auth ticket and the account form. Nothing here fails loudly at
/// runtime — a mismatched id just leaves the page rendering in the default colors — so the
/// checks have to be mechanical.
/// </summary>
public class ThemeTests
{
    public static IEnumerable<(string, string)> AllPalettes() =>
        Themes.Light.Concat(Themes.Dark).Select(theme => (theme.Id, theme.Mode));

    /// <summary>
    /// themes.css is generated by scripts/build-themes.py, so the list here and the blocks
    /// there are edited separately and can drift.
    /// </summary>
    [Test]
    [MethodDataSource(nameof(AllPalettes))]
    public async Task Every_palette_has_a_block_in_the_stylesheet(string id, string mode)
    {
        _ = mode;

        using var app = new TestApp();
        var css = await app.CreateClient().GetStringAsync("/css/themes.css", TestContext.Current!.Execution.CancellationToken);

        await Assert.That(css).Contains($":root[data-theme-name=\"{id}\"]");
    }

    [Test]
    public async Task The_two_palette_lists_do_not_overlap()
    {
        await Assert.That(Themes.Light.Select(t => t.Id).Intersect(Themes.Dark.Select(t => t.Id))).IsEmpty();
    }

    [Test]
    public async Task Each_list_reports_the_mode_it_is_filed_under()
    {
        await Assert.That(Themes.Light).All(t => t.Mode == Themes.LightMode);
        await Assert.That(Themes.Dark).All(t => t.Mode == Themes.DarkMode);
    }

    // ---- normalization -------------------------------------------------

    /// <summary>
    /// A dark scheme selected for the light side would emit a data-theme-name whose palette
    /// assumes the opposite background — dark text on dark. Falling back to the stock look
    /// is the only safe reading.
    /// </summary>
    [Test]
    public async Task A_palette_from_the_other_mode_is_rejected()
    {
        await Assert.That(Themes.Normalize("nord", Themes.LightMode)).IsNull();
        await Assert.That(Themes.Normalize("solarized-light", Themes.DarkMode)).IsNull();
    }

    [Test]
    [Arguments(null)]
    [Arguments("")]
    [Arguments("no-such-theme")]
    [Arguments("NORD")]
    public async Task Anything_that_is_not_a_known_palette_is_rejected(string? id)
    {
        await Assert.That(Themes.Normalize(id, Themes.DarkMode)).IsNull();
    }

    [Test]
    public async Task A_palette_belonging_to_the_mode_is_kept()
    {
        await Assert.That(Themes.Normalize("nord", Themes.DarkMode)).IsEqualTo("nord");
        await Assert.That(Themes.Normalize("solarized-light", Themes.LightMode)).IsEqualTo("solarized-light");
    }

    // ---- the map handed to the pre-paint script ------------------------

    [Test]
    public async Task The_palette_map_carries_both_sides()
    {
        var map = Deserialize(Themes.PaletteMapJson("gruvbox-light", "dracula"));

        await Assert.That(map[Themes.LightMode]).IsEqualTo("gruvbox-light");
        await Assert.That(map[Themes.DarkMode]).IsEqualTo("dracula");
    }

    /// <summary>
    /// The script tests the looked-up value for truthiness, so an unset side has to be absent
    /// rather than present-and-null.
    /// </summary>
    [Test]
    public async Task An_unset_side_is_left_out_of_the_map_entirely()
    {
        var map = Deserialize(Themes.PaletteMapJson(null, "nord"));

        await Assert.That(map.ContainsKey(Themes.LightMode)).IsFalse();
        await Assert.That(map[Themes.DarkMode]).IsEqualTo("nord");
    }

    [Test]
    public async Task The_map_is_valid_json_when_nothing_is_set()
    {
        await Assert.That(Deserialize(Themes.PaletteMapJson(null, null))).IsEmpty();
    }

    private static Dictionary<string, string> Deserialize(string json) =>
        JsonSerializer.Deserialize<Dictionary<string, string>>(json)!;

    // ---- the auth ticket -----------------------------------------------

    [Test]
    public async Task The_ticket_carries_both_palettes()
    {
        var principal = UserPrincipal.Create(
            new User { Id = 1, Username = "someone", LightTheme = "catppuccin-latte", DarkTheme = "monokai" });

        await Assert.That(UserPrincipal.GetLightTheme(principal)).IsEqualTo("catppuccin-latte");
        await Assert.That(UserPrincipal.GetDarkTheme(principal)).IsEqualTo("monokai");
    }

    /// <summary>
    /// Null and "no claim" have to read back the same, because that is what
    /// <see cref="RevalidateUserEvents"/> compares the row against when deciding whether the
    /// cookie has gone stale. An empty-string claim would make every request see a difference
    /// and reissue the ticket forever.
    /// </summary>
    [Test]
    public async Task An_unset_palette_leaves_no_claim_behind()
    {
        var principal = UserPrincipal.Create(new User { Id = 1, Username = "someone" });

        await Assert.That(UserPrincipal.GetLightTheme(principal)).IsNull();
        await Assert.That(UserPrincipal.GetDarkTheme(principal)).IsNull();
        await Assert.That(principal.Claims).DoesNotContain(c => c.Type == UserPrincipal.LightThemeClaim);
        await Assert.That(principal.Claims).DoesNotContain(c => c.Type == UserPrincipal.DarkThemeClaim);
    }

    [Test]
    public async Task An_anonymous_visitor_has_no_palettes()
    {
        var anonymous = new ClaimsPrincipal(new ClaimsIdentity());

        await Assert.That(UserPrincipal.GetLightTheme(anonymous)).IsNull();
        await Assert.That(UserPrincipal.GetDarkTheme(anonymous)).IsNull();
    }
}
